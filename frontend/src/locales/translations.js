/**
 * Get a translation by dot-notation key path.
 * Falls back to English if the key is missing in the target language.
 *
 * @param {string} keyPath  e.g. 'dashboard.cityRisk'
 * @param {string} lang     'en' | 'hi' | 'gu'
 * @returns {*}
 */
export function t(keyPath, lang = 'en') {
  const keys = keyPath.split('.');
  const pick = (obj) => keys.reduce((acc, k) => (acc && acc[k] !== undefined ? acc[k] : undefined), obj);
  const result = pick(translations[lang] || {});
  if (result !== undefined) return result;
  return pick(translations.en) ?? keyPath;
}

export function getTranslations(lang = 'en') {
  return translations[lang] || translations.en;
}

